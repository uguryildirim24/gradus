"""Profile NextGig into data/raw/open/nextgig_profile.md.
Run: uv run python scripts/profile_nextgig.py
"""
import json
from pathlib import Path

import pandas as pd

ROOT = Path(__file__).resolve().parents[1] / "data" / "raw" / "open"
d = pd.read_parquet(ROOT / "nextgig" / "nextgig_jobs_2026-06.parquet")
N = len(d)
out = []
w = out.append


def filled(s: pd.Series) -> pd.Series:
    """True where the field carries a value (not null, empty, [] or 'none'-like)."""
    t = s.astype("string").str.strip()
    return s.notna() & ~t.str.lower().isin(["", "[]", "none", "null", "n/a", "unknown", "nan"])


def pct(x) -> str:
    return f"{x:,} ({x / N:.1%})"


def vc(col: str, n: int = 15) -> None:
    v = d.loc[filled(d[col]), col].value_counts()
    w(f"\n`{col}` ({len(v)} distinct, top {n}):\n")
    w("| value | rows | share of filled |")
    w("|---|---|---|")
    for k, c in v.head(n).items():
        w(f"| {str(k)[:60]} | {c:,} | {c / v.sum():.1%} |")


w("# NextGig profile\n")
w(f"Source: `nextgig/nextgig_jobs_2026-06.parquet`, {N:,} rows x {d.shape[1]} columns. "
  "Generated by `scripts/profile_nextgig.py`.\n")
w("## Fill rates (all columns)\n")
w("| column | filled | fill rate | note |")
w("|---|---|---|---|")
for c in d.columns:
    f = int(filled(d[c]).sum())
    w(f"| {c} | {f:,} | {f / N:.1%} | |")

w("\n## Distributions")
for c in ["ats_name", "industry", "function", "occupational_category", "employment_type",
          "work_model", "experience_level", "job_level_normalized", "education_level",
          "country", "visa_sponsorship_available", "work_authorization_requirements",
          "security_clearance", "relocation_assistance", "salary_currency"]:
    vc(c, 20 if c in ("country", "function", "industry") else 12)

# list-valued fields
def lens(col):
    def f(x):
        try:
            v = json.loads(x)
            return len(v) if isinstance(v, list) else 1
        except Exception:
            return 0
    return d[col].map(lambda x: f(x) if isinstance(x, str) else 0)

w("\n## List fields (JSON strings)\n")
w("| column | rows with >=1 item | median items (where present) |")
w("|---|---|---|")
for c in ["skills_required", "minimum_qualifications", "preferred_qualifications",
          "responsibilities", "certifications", "languages_required", "benefits"]:
    l = lens(c)
    w(f"| {c} | {pct(int((l > 0).sum()))} | {l[l > 0].median():.0f} |")

top_skills = {}
for x in d["skills_required"].dropna().head(60000):
    try:
        for s in json.loads(x):
            top_skills[s] = top_skills.get(s, 0) + 1
    except Exception:
        pass
w("\nTop skills_required values (first 60k rows):\n")
w(", ".join(f"{k} ({v})" for k, v in sorted(top_skills.items(), key=lambda kv: -kv[1])[:40]))

w("\n## Languages\n")
lang = d["languages_required"].dropna()
cnt = {}
for x in lang:
    try:
        for s in json.loads(x):
            s = s if isinstance(s, str) else json.dumps(s)
            cnt[s] = cnt.get(s, 0) + 1
    except Exception:
        pass
w(f"`languages_required` filled on {pct(int(filled(d['languages_required']).sum()))}. Top: " +
  ", ".join(f"{k} ({v})" for k, v in sorted(cnt.items(), key=lambda kv: -kv[1])[:20]))
w("\nPosting text language: `job_description` is described by the card as English (en); "
  "non-ASCII share of descriptions: "
  f"{(d['job_description'].dropna().str.contains(r'[^\x00-\x7f]{3,}', regex=True)).mean():.1%} "
  "(rough proxy for non-English text).")

w("\n## Description length\n")
L = d["job_description"].dropna().str.len()
w(f"job_description chars: median {L.median():.0f}, p10 {L.quantile(.1):.0f}, "
  f"p90 {L.quantile(.9):.0f}, max {L.max():,}.")

# usable signals
deg = filled(d["education_level"])
yrs = d["years_experience_numeric"].notna()
sk = lens("skills_required") > 0
mq = lens("minimum_qualifications") > 0
loc = filled(d["country"]) | filled(d["city"]) | filled(d["location_resolved"])
locfull = filled(d["country"]) & filled(d["city"])
spons = filled(d["visa_sponsorship_available"])
wauth = filled(d["work_authorization_requirements"])
clr = filled(d["security_clearance"])
auth = spons | wauth

w("\n## Usable-signal counts\n")
w("Counts of rows where the structured field carries a value. 'Text signal' rows would "
  "need regex on `minimum_qualifications` / `job_description`, counted below.\n")
w("| signal | rows | share |")
w("|---|---|---|")
for name, m in [("degree (education_level)", deg), ("years (years_experience_numeric)", yrs),
                ("skills (skills_required, >=1)", sk), ("min qualifications (>=1 item)", mq),
                ("location (country or city or location_resolved)", loc),
                ("location country+city", locfull),
                ("sponsorship (visa_sponsorship_available)", spons),
                ("work authorization text (work_authorization_requirements)", wauth),
                ("sponsorship or work-authorization", auth),
                ("security clearance", clr)]:
    w(f"| {name} | {int(m.sum()):,} | {m.mean():.1%} |")

# years from text
mqtext = d["minimum_qualifications"].fillna("").str.lower()
yr_text = mqtext.str.contains(r"\b\d+\s*\+?\s*(?:-\s*\d+\s*)?years?\b", regex=True)
deg_text = mqtext.str.contains(r"bachelor|master|\bphd\b|doctorate|associate|high school|\bdegree\b|\bmba\b", regex=True)
w("\nFrom `minimum_qualifications` text (regex, rough):\n")
w(f"- mentions N years: {pct(int(yr_text.sum()))}; of those without numeric years column: "
  f"{pct(int((yr_text & ~yrs).sum()))}")
w(f"- mentions a degree: {pct(int(deg_text.sum()))}; of those without education_level: "
  f"{pct(int((deg_text & ~deg).sum()))}")
spons_text = (d["job_description"].fillna("") + " " + mqtext).str.lower().str.contains(
    r"sponsor|work authori[sz]ation|authorized to work|eligib\w+ to work|right to work", regex=True)
w(f"- sponsorship / work-authorization wording in description or min quals: "
  f"{pct(int(spons_text.sum()))}")

vs = d["visa_sponsorship_available"].astype("string").str.lower().fillna("")
clean_spons = vs.str.contains(r"sponsor|h-?1b|visa|citizen|clearance|\bno\b|\byes\b|^true$|^false$", regex=True)
w(f"- clean sponsorship signal (value actually about sponsorship/visa/citizenship, not a stray "
  f"location or tag like 'US'/'WW'): {pct(int(clean_spons.sum()))}")
w(f"- clean sponsorship, explicit denial (no / false / no sponsorship / citizenship required): "
  f"{pct(int(vs.str.contains(r'^no\b|^false$|no (?:new )?(?:h-?1b )?sponsor|citizen|not (?:provide|offer|sponsor)', regex=True).sum()))}")
w(f"- clean sponsorship, explicit yes (yes / true / transfer welcomed): "
  f"{pct(int(vs.str.contains(r'^yes|^true$|welcome|available|will sponsor', regex=True).sum()))}")
w("- `security_clearance` and `work_authorization_requirements` hold many stray tags "
  "('Retail', 'On-site', 'Drug-free workplace'); only the explicit clearance words are usable.")
clr_clean = d["security_clearance"].astype("string").str.lower().fillna("").str.contains(
    r"secret|top secret|ts/sci|clearance|public trust|polygraph", regex=True)
w(f"- real clearance requirement (secret / TS / public trust / polygraph wording): {pct(int(clr_clean.sum()))}")
combo = deg & yrs & sk & loc
w("\n## Combined\n")
w(f"- rows with degree + years + skills + location all structured: {pct(int(combo.sum()))}")
combo2 = (deg | deg_text) & (yrs | yr_text) & sk & loc
w(f"- same, allowing text-derived degree/years: {pct(int(combo2.sum()))}")
combo3 = combo2 & auth
w(f"- same as above plus structured sponsorship/work-auth: {pct(int(combo3.sum()))}")
rich = (sk & loc & (deg | deg_text | yrs | yr_text))
w(f"- skills + location + at least one of degree/years: {pct(int(rich.sum()))}")

w("\n## Cross-tab: country x signals (top 12 countries)\n")
top = d.loc[filled(d['country']), 'country'].value_counts().head(12).index
w("| country | rows | years | degree | skills | sponsorship |")
w("|---|---|---|---|---|---|")
for c in top:
    m = d["country"] == c
    w(f"| {c} | {int(m.sum()):,} | {yrs[m].mean():.0%} | {deg[m].mean():.0%} | {sk[m].mean():.0%} | {spons[m].mean():.0%} |")

(ROOT / "nextgig_profile.md").write_text("\n".join(out) + "\n")
print("\n".join(out))
